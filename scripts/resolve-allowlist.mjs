#!/usr/bin/env node
/**
 * Resolve the Meirei allowlist (xStocks + cash) from the Onchain OS CLI.
 *
 * Read-only: runs `onchainos token search` and prints a ready-to-paste
 * `ALLOWLIST` block for src/allowlist.ts. Never signs or broadcasts anything.
 *
 * Usage:  node scripts/resolve-allowlist.mjs [chain]
 *         npm run verify:allowlist
 */
import { execFileSync } from "node:child_process";

const CHAIN = process.argv[2] || "xlayer"; // xlayer = chain 196, xlayer_test = 1952

// symbol -> preferred token name substrings (first match wins)
const WANTED = [
  ["AAPLx", ["Apple xStock"]],
  ["MSFTx", ["Microsoft xStock"]],
  ["NVDAx", ["NVIDIA xStock"]],
  ["GOOGLx", ["Alphabet xStock", "Google xStock"]],
  ["AMZNx", ["Amazon xStock"]],
  ["METAx", ["Meta xStock"]],
  ["TSLAx", ["Tesla xStock"]],
  ["USDG", ["Global Dollar"]],
  ["USDC", ["USD Coin"]],
];

const DENY = /^(w|SY-|aXlr)/i; // wrapped / synthetic / yield-bearing variants are NOT allowed

function search(query) {
  const raw = execFileSync("onchainos", ["token", "search", "--query", query, "--chain", CHAIN, "--limit", "20"], {
    encoding: "utf8",
    windowsHide: true,
  });
  const parsed = JSON.parse(raw);
  return Array.isArray(parsed?.data) ? parsed.data : [];
}

function pick(symbol, preferredNames) {
  const candidates = search(symbol).filter(
    (t) => t.tokenSymbol === symbol && !DENY.test(t.tokenSymbol)
  );
  if (!candidates.length) return null;
  const byName = candidates.find((t) =>
    preferredNames.some((n) => String(t.tokenName || "").includes(n))
  );
  const best = byName || candidates[0];
  return { symbol, address: best.tokenContractAddress, decimals: Number(best.decimal), name: best.tokenName };
}

const resolved = [];
const missing = [];

for (const [symbol, names] of WANTED) {
  const hit = pick(symbol, names);
  if (hit) resolved.push(hit);
  else missing.push(symbol);
}

console.log(`// Chain ${CHAIN} — generated by scripts/resolve-allowlist.mjs`);
console.log("export const ALLOWLIST: AllowlistEntry[] = [");
for (const e of resolved) {
  console.log(`  { symbol: "${e.symbol}", address: "${e.address}", decimals: ${e.decimals}, name: "${e.name}" },`);
}
console.log("];");

if (missing.length) {
  console.error(`\n!! Not found on ${CHAIN}: ${missing.join(", ")}`);
  console.error("   A missing symbol must NOT stay in the allowlist — mandates naming it will throw.");
  process.exitCode = 1;
}